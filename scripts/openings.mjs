// scripts/openings — generates src/endgame/openings-data.js from the lichess-org/chess-openings TSV files (a.tsv … e.tsv).
//
//   node scripts/openings.mjs [dir]      dir defaults to ../stepchess-data/openings (outside the repo)
//
// Every line is replayed with the engine from the start position; one illegal or unreadable move stops the run.
// Lines are stored as UCI move strings. The TSV files are data only: nothing in them is executed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Position, parseMove, moveToUci, NO_MOVE } from '../src/core/index.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.resolve(process.argv[2] ?? path.join(root, '..', 'stepchess-data', 'openings'));
const out = path.join(root, 'src', 'endgame', 'openings-data.js');

const fail = (text) => {
    console.error(`openings: ${text}`);
    process.exit(1);
};

const entries = [];
for (const file of ['a', 'b', 'c', 'd', 'e']) {
    const tsv = path.join(dir, `${file}.tsv`);
    if (!fs.existsSync(tsv)) fail(`${tsv} is missing`);
    const rows = fs.readFileSync(tsv, 'utf8').split(/\r?\n/).filter(Boolean);
    if (rows[0].trim() !== 'eco\tname\tpgn') fail(`${tsv}: unexpected header ${JSON.stringify(rows[0])}`);
    for (const [n, row] of rows.slice(1).entries()) {
        const where = `${file}.tsv line ${n + 2}`;
        const cells = row.split('\t');
        if (cells.length !== 3) fail(`${where}: expected 3 columns`);
        const [eco, name, pgn] = cells;
        if (!/^[A-E]\d\d$/.test(eco)) fail(`${where}: bad ECO ${JSON.stringify(eco)}`);
        const pos = Position.fromFen(Position.START_FEN);
        const uci = [];
        for (const token of pgn.split(/\s+/).filter((t) => !/^\d+\.+$/.test(t))) {
            const m = parseMove(pos, token.replace(/^\d+\.+/, ''));
            if (m === NO_MOVE) fail(`${where} (${name}): illegal move ${token} after ${uci.join(' ')}`);
            uci.push(moveToUci(m));
            pos.make(m);
        }
        if (uci.length === 0) fail(`${where} (${name}): no moves`);
        entries.push([eco, name, uci.join(' ')]);
    }
}

const date = new Date().toISOString().slice(0, 10);
const header = `// endgame/openings-data — GENERATED by scripts/openings.mjs, do not edit.
// Source: https://github.com/lichess-org/chess-openings (a.tsv … e.tsv), licence CC0 (public domain). Generated ${date}.
// OPENINGS = [[eco, name, uciLine], …]: every named line as UCI moves from the start position. The lookup by
// position hash is built lazily in openings.js.
`;
const body = `export const OPENINGS = [\n${entries.map((e) => `    ${JSON.stringify(e)},`).join('\n')}\n];\n`;
let text = header + body;
try {
    const prettier = await import('prettier');
    const options = await prettier.resolveConfig(out);
    text = await prettier.format(text, { ...options, filepath: out });
} catch (e) {
    console.warn(`openings: prettier not applied (${e.message}); run npm run format`);
}
fs.writeFileSync(out, text);
console.log(`openings: ${entries.length} lines -> ${pathToFileURL(out).pathname} (${(text.length / 1024).toFixed(0)} KB)`);
